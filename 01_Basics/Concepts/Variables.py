# Variables

name = "Shasumith"
age = 19
is_student = True

print(name)
print(age)
print(is_student)


# Multiple Variable Assignment

x, y, z = 10, 20, 30

print(x)
print(y)
print(z)


# Same Value to Multiple Variables

a = b = c = 100

print(a)
print(b)
print(c)


# Updating a Variable

score = 85
print(score)

score = 95
print(score)


# Variables of Different Data Types

city = "Mumbai"
temperature = 32.5
population = 20400000
is_raining = False

print(city)
print(temperature)
print(population)
print(is_raining)