# Data Types

# String
name = "Shasumith"
print(name)
print(type(name))

# Integer
age = 19
print(age)
print(type(age))

# Float
cgpa = 9.25
print(cgpa)
print(type(cgpa))

# Boolean
is_student = True
print(is_student)
print(type(is_student))

# Complex Number
complex_num = 3 + 4j
print(complex_num)
print(type(complex_num))

# List   
fruits = ["Apple", "Banana", "Mango"]
print(fruits)
print(type(fruits))

# Tuple
colors = ("Red", "Green", "Blue")
print(colors)
print(type(colors))

# Set
numbers = {10, 20, 30, 40}
print(numbers)
print(type(numbers))

# Dictionary
student = {
    "name": "Shasumith",
    "age": 19,
    "cgpa": 9.25
}
print(student)
print(type(student))

# NoneType
value = None
print(value)
print(type(value))